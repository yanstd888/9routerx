func main() {
	readmePath := flag.String("readme", "README.md", "markdown file rendered as the site homepage")
	assetsDir := flag.String("assets", "site", "directory of static files copied verbatim into the site")
	outDir := flag.String("out", "_site", "directory the site is written to")
	wikiDir := flag.String("wiki", "wiki", "directory of wiki pages rendered next to the README")
	repo := flag.String("repo", "yanstd888/9routerx", "owner/name used to resolve relative repository links")
	flag.Parse()

	// The brand icons ship before anything renders, because both templates link
	// them from every page: a missing icon would publish a site whose favicon
	// and og:image 404 everywhere at once. Failing the build here — not
	// skipping quietly — is what keeps the Pages output from drifting into a
	// half-branded site when a rename in web/public lands without a template
	// change.
	if err := copyIcons(webPublicDir, *outDir); err != nil {
		fmt.Fprintln(os.Stderr, "sitegen:", err)
		os.Exit(1)
	}

	// The wiki renders BEFORE the README so the landing wins index.html. Both
	// used to write that name — wiki/index.md renders with the slug "index" —
	// and the Pages workflow's contract is that the project page is the site's
	// own front door ("the README becomes index.html", see TestGenerate and
	// the pages.yml entry-point assert). Generating in the other order let the
	// wiki home silently replace it as the site's homepage. wiki/index.md is
	// still unpublished (see generateWiki): its entry-point role moved to the
	// landing and readme.html.
	if info, err := os.Stat(*wikiDir); err == nil && info.IsDir() {
		if err := generateWiki(*wikiDir, *outDir, *repo); err != nil {
			fmt.Fprintln(os.Stderr, "sitegen:", err)
			os.Exit(1)
		}
	}

	if err := generate(*readmePath, *assetsDir, *outDir, *repo, collectHeroStats(*wikiDir)); err != nil {
		fmt.Fprintln(os.Stderr, "sitegen:", err)
		os.Exit(1)
	}
	if err := writeLLMFiles(*readmePath, *assetsDir, *wikiDir, *outDir); err != nil {
		fmt.Fprintln(os.Stderr, "sitegen:", err)
		os.Exit(1)
	}
	if err := writeCrawlFiles(*outDir, time.Now()); err != nil {
		fmt.Fprintln(os.Stderr, "sitegen:", err)
		os.Exit(1)
	}
}

func generate(readmePath, assetsDir, outDir, repo string, stats heroStats) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}

	body, err := renderMarkdown(readmePath, outDir, repo)
	if err != nil {
		return fmt.Errorf("render %s: %w", readmePath, err)
	}

	if err := copyFile(filepath.Join(assetsDir, "style.css"), filepath.Join(outDir, "style.css")); err != nil {
		return err
	}

	// The masthead mark on every page: site/logo-9routerx-128.png, the 128px
	// resize of web/public/logo-9routerx.png (generated by the sitegen asset
	// step, committed alongside this file — the 2048px original is 1.9 MB and
	// must never load in a header). Missing asset = hard error, the same
	// philosophy as copyIcons: both templates reference it, so a silent skip
	// would publish a site-wide broken image.
	logo := filepath.Join(assetsDir, "logo-9routerx-128.png")
	if _, err := os.Stat(logo); err != nil {
		return fmt.Errorf("masthead logo %s is missing from the site assets: %w", logo, err)
	}
	if err := copyFile(logo, filepath.Join(outDir, "logo-9routerx-128.png")); err != nil {
		return err
	}

	// The redirect answers on /tg.html, on /tg, and on /tg/. GitHub Pages
	// resolves a bare /tg to tg.html, but a crawler or a mistyped trailing
	// slash should not land on the 404 page, so all three are written from the
	// one source file. See site/tg.html for why the invite link lives there.
	for _, dest := range []string{"tg.html", "tg/index.html"} {
		if err := copyFile(filepath.Join(assetsDir, "tg.html"), filepath.Join(outDir, filepath.FromSlash(dest))); err != nil {
			return err
		}
	}

	// llms.txt hands LLM crawlers a curated map of the site (site/llms.txt).
	// Listed explicitly like the other assets because -assets is never copied
	// wholesale — an unlisted file would silently never ship.
	if err := copyFile(filepath.Join(assetsDir, "llms.txt"), filepath.Join(outDir, "llms.txt")); err != nil {
		return err
	}

	page, err := renderPage(body, repo, stats)
	if err != nil {
		return fmt.Errorf("render page: %w", err)
	}
	if err := writeFile(filepath.Join(outDir, "index.html"), page); err != nil {
		return err
	}

	// The README keeps its own page in the same chrome, its H1 intact — the
	// page belongs to it. Body passes through unescaped because it is this
	// repository's own README: the same file GitHub renders for everyone
	// reading the repo.
	article, err := renderReadmePage(body, repo)
	if err != nil {
		return fmt.Errorf("render readme page: %w", err)
	}
	return writeFile(filepath.Join(outDir, "readme.html"), article)
}

func renderMarkdown(readmePath, outDir, repo string) ([]byte, error) {
	src, err := os.ReadFile(readmePath)
	if err != nil {
		return nil, fmt.Errorf("read: %w", err)
	}

	md := goldmark.New(
		goldmark.WithExtensions(extension.GFM),
		goldmark.WithParserOptions(parser.WithAutoHeadingID(), parser.WithAttribute()),
		// The README wraps its title block in <div align="center"> and hides the
		// environment variable table in <details>. Both are the author's markup
		// for GitHub's own renderer, so dropping them here would silently delete
		// content the repository depends on.
		goldmark.WithRendererOptions(goldmarkhtml.WithUnsafe()),
	)

	doc := md.Parser().Parse(text.NewReader(src))

	images := map[string]struct{}{}
	rewriteRelativeLinks(doc, repo, readmePath, images)

	for rel := range images {
		if err := copyFile(filepath.Join(filepath.Dir(readmePath), filepath.FromSlash(rel)), filepath.Join(outDir, filepath.FromSlash(rel))); err != nil {
			return nil, err
		}
	}

	var buf bytes.Buffer
	if err := md.Renderer().Render(&buf, src, doc); err != nil {
		return nil, fmt.Errorf("render html: %w", err)
	}
	// The README carries wide tables too (the environment table, the
	// screenshot gallery), so it gets the same scroll wrappers as the wiki
	// pages — the deploy asserts the pairing across the whole site. After
	// that, injectIcons restores the section and feature markers the
	// emoji-free markdown sources no longer carry (see icons.go): the same
	// post-render point wrapTables runs at, on the exact markup the browser
	// gets.
	return []byte(renderSvgCodeSpans(injectIcons(wrapTables(buf.String())))), nil
}

// svgCodeSpan matches a goldmark code span whose entire body is one inline
// <svg> element, escaped the way code spans are.
var svgCodeSpan = regexp.MustCompile(`(?s)<code>(&lt;svg\b.*?&lt;/svg&gt;)</code>`)

// renderSvgCodeSpans turns a code span that contains nothing but an inline
// <svg> into the real icon. The README's Key Features table writes each row
// icon as a backticked SVG, and goldmark correctly escapes a code span — so
// the first table column published a wall of literal markup and every row
// grew to the height of that text. The page already trusts this repository's
// own HTML (WithUnsafe), so the span is unescaped and tagged with the same
// .ico class every injected icon carries, which lets the shared sizing CSS in
// style.css treat it like the others. A span with any other content is left
// untouched, and the pass is idempotent: once unescaped, the output no longer
// matches the escaped form.
func renderSvgCodeSpans(markup string) string {
	return svgCodeSpan.ReplaceAllStringFunc(markup, func(span string) string {
		match := svgCodeSpan.FindStringSubmatch(span)
		if match == nil {
			return span
		}
		decoded := strings.TrimSpace(html.UnescapeString(match[1]))
		if !strings.HasPrefix(decoded, "<svg") || !strings.HasSuffix(decoded, "</svg>") {
			return span
		}
		return strings.Replace(decoded, "<svg", `<svg class="ico"`, 1)
	})
}

// rewriteRelativeLinks points every repository-relative link at github.com and
// records the image ones for copying. Anchors, absolute URLs and site-absolute
// paths are left untouched.
//
// Every image — remote badges included — is marked lazy and async, matching
// the wiki renderer: the homepage ships the screenshot table and the badge
// row, and the Pages deploy asserts that eager images cannot happen. Local
// images additionally carry width and height read from the file, so the
// browser reserves the box before the bytes arrive.
func rewriteRelativeLinks(doc ast.Node, repo, readmePath string, images map[string]struct{}) {
	_ = ast.Walk(doc, func(node ast.Node, entering bool) (ast.WalkStatus, error) {
		if !entering {
			return ast.WalkContinue, nil
		}
		switch n := node.(type) {
		case *ast.Link:
			n.Destination = blobURL(repo, n.Destination)
		case *ast.Image:
			// A badge hosted on shields.io is an absolute URL and must be left
			// alone; isAsset only matches extension, so the scheme check that
			// blobURL does has to come first or every badge is "copied" from a
			// path named after its https:// prefix.
			n.SetAttributeString("loading", []byte("lazy"))
			n.SetAttributeString("decoding", []byte("async"))
			if hasScheme(string(n.Destination)) || strings.HasPrefix(string(n.Destination), "/") {
				return ast.WalkContinue, nil
			}
			if !isAsset(n.Destination) {
				n.Destination = blobURL(repo, n.Destination)
				return ast.WalkContinue, nil
			}
			images[string(n.Destination)] = struct{}{}
			if w, h, ok := imageSize(filepath.Join(filepath.Dir(readmePath), filepath.FromSlash(string(n.Destination)))); ok {
				n.SetAttributeString("width", []byte(strconv.Itoa(w)))
				n.SetAttributeString("height", []byte(strconv.Itoa(h)))
			}
		}
		return ast.WalkContinue, nil
	})
}

// blobURL turns `docs/DATABASE.md#section` into its github.com blob URL. Input
// that does not name a repository file is returned unchanged.
func blobURL(repo string, dest []byte) []byte {
	raw := string(dest)
	if raw == "" || strings.HasPrefix(raw, "#") || strings.HasPrefix(raw, "/") || hasScheme(raw) {
		return dest
	}
	// A link pointing outside the repository cannot be resolved against it.
	if strings.HasPrefix(raw, "..") {
		return dest
	}

	file, fragment, hasFragment := strings.Cut(raw, "#")
	if file == "" {
		return dest
	}

	url := fmt.Sprintf("https://github.com/%s/blob/main/%s", repo, file)
	if hasFragment {
		url += "#" + fragment
	}
	return []byte(url)
}

func hasScheme(raw string) bool {
	idx := strings.Index(raw, ":")
	if idx < 1 {
		return false
	}
	scheme := raw[:idx]
	for i, r := range scheme {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9', r == '+', r == '-', r == '.':
			if i == 0 {
				return false
			}
		default:
			return false
		}
	}
	return true
}

func isAsset(dest []byte) bool {
	file, _, _ := strings.Cut(string(dest), "#")
	switch strings.ToLower(path.Ext(file)) {
	case ".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".avif", ".ico":
		return true
	}
	return false
}

// renderPage renders the homepage. readmeBody is not embedded — the landing is
// pure design — but the README's own FAQ section still feeds the page's
// FAQ JSON-LD, so the schema and the visible FAQ section stay one source.
func renderPage(readmeBody []byte, repo string, stats heroStats) ([]byte, error) {
	tmpl, err := template.New("page").Funcs(template.FuncMap{
		"blob": func(p string) string {
			return fmt.Sprintf("https://github.com/%s/blob/main/%s", repo, p)
		},
	}).Parse(pageTemplate)
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	data := struct {
		Repo     string
		Stats    heroStats
		Software json.RawMessage
		FAQ      json.RawMessage
		Year     int
	}{Repo: repo, Stats: stats, Software: softwareSchema(stats.Version), FAQ: faqSchema(string(readmeBody)), Year: time.Now().UTC().Year()}

	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute template: %w", err)
	}
	return buf.Bytes(), nil
}

// renderReadmePage renders readme.html: the README article in the shared
// chrome. The README's first H1 stays an H1 — the page belongs to it, and the
// landing no longer embeds the body, so there is no second H1 to collide with.
func renderReadmePage(body []byte, repo string) ([]byte, error) {
	tmpl, err := template.New("readme").Funcs(template.FuncMap{
		"blob": func(p string) string {
			return fmt.Sprintf("https://github.com/%s/blob/main/%s", repo, p)
		},
	}).Parse(readmeTemplate)
	if err != nil {
		return nil, fmt.Errorf("parse readme template: %w", err)
	}

	var buf bytes.Buffer
	data := struct {
		Body template.HTML
		Repo string
		Year int
	}{Body: template.HTML(body), Repo: repo, Year: time.Now().UTC().Year()}

	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute readme template: %w", err)
	}
	return buf.Bytes(), nil
}

func copyFile(src, dest string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return fmt.Errorf("read %s: %w", src, err)
	}
	return writeFile(dest, data)
}

// webPublicDir is where the brand icons live in the repository: next to the
// dashboard, whose own <head> links the same files. The path is relative
// because both the Pages workflow and a local render run the generator from
// the repository root.
const webPublicDir = "web/public"

// brandIcons is every icon file the published site carries. Three are linked
// by the favicon block both templates emit, logo-9routerx.png is the og:image
// on every page, and the rest exist so a browser or a crawler that asks for
// the sizes the favicon spec names (16, 180, 192, 512) finds a real file
// rather than a 404 in the crawler's log.
var brandIcons = []string{
	"favicon.ico",
	"favicon-16x16.png",
	"favicon-32x32.png",
	"apple-touch-icon.png",
	"android-chrome-192x192.png",
	"android-chrome-512x512.png",
	"logo-9routerx.png",
}

// copyIcons copies each brand icon into the site root, where the templates'
// relative favicon and og:image references resolve. A missing icon is a hard
// error naming the file, never a skip: the favicon links ship on every page,
// so a silent skip would publish a site-wide broken reference and fail
// nothing until a crawler hit it.
func copyIcons(iconsDir, outDir string) error {
	for _, name := range brandIcons {
		src := filepath.Join(iconsDir, name)
		if _, err := os.Stat(src); err != nil {
			return fmt.Errorf("brand icon %s is missing from %s: %w", name, iconsDir, err)
		}
		if err := copyFile(src, filepath.Join(outDir, name)); err != nil {
			return err
		}
	}
	return nil
}

func writeFile(dest string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return fmt.Errorf("create directory for %s: %w", dest, err)
	}
	if err := os.WriteFile(dest, data, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", dest, err)
	}
	return nil
}
